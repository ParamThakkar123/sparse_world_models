"""Regenerate the CVPR-format body from the ICLR manuscript.

``paper/main.tex`` is the single source of the prose. This script writes
``paper_cvpr/body.tex`` (main text) and ``paper_cvpr/supp.tex`` (appendices, which become the
supplementary material) with the changes the two-column CVPR layout needs, so the two versions
cannot drift. Never edit body.tex or supp.tex by hand; edit paper/main.tex and rerun:

    python paper_cvpr/convert.py
    cd paper_cvpr && pdflatex main && bibtex main && pdflatex main && pdflatex main
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "paper" / "main.tex"

WIDE_TABLE_CAPTIONS = ("The audit battery across", "Five published object-centric")


def split_source(text: str) -> tuple[str, str]:
    body = text.split(r"\maketitle", 1)[1]
    main, rest = body.split(r"\bibliographystyle{iclr2027_conference}", 1)
    appendix = rest.split(r"\appendix", 1)[1].split(r"\end{document}", 1)[0]
    return main, appendix


def shared(text: str) -> str:
    text = text.replace(r"\input{tables/", r"\input{../paper/tables/")
    text = text.replace(r"width=0.92\textwidth", r"width=\linewidth")
    text = text.replace("Sections~", "Secs.~").replace("Section~", "Sec.~")
    return text


def widen_tables(text: str) -> str:
    """Promote the two wide tables to table* so they span both columns."""
    out, pos = [], 0
    while True:
        start = text.find(r"\begin{table}", pos)
        if start < 0:
            out.append(text[pos:])
            return "".join(out)
        end = text.find(r"\end{table}", start) + len(r"\end{table}")
        block = text[start:end]
        if any(c in block for c in WIDE_TABLE_CAPTIONS):
            block = block.replace(r"\begin{table}", r"\begin{table*}", 1)
            block = block.replace(r"\end{table}", r"\end{table*}", 1)
        out.append(text[pos:start])
        out.append(block)
        pos = end


def convert_main(text: str) -> str:
    text = widen_tables(shared(text))
    text = text.replace(r"Appendix~\ref{", r"Supp.~\ref{")
    # The unnumbered closing statements become run-in paragraphs; \sloppy keeps the long
    # \texttt paths from stretching the narrow column.
    text = text.replace(r"\section*{Reproducibility statement}",
                        "{\\sloppy\n\\paragraph{Reproducibility.}")
    text = text.replace(r"\section*{Use of large language models}",
                        r"\paragraph{Use of large language models.}")
    if "{\\sloppy" in text:
        text = text.rstrip() + "\n\\par}\n"
    return text


def convert_supp(text: str) -> str:
    text = shared(text)
    text = text.replace(r"Table~\ref{tab:battery}", r"Tab.~\ref{tab:battery} of the main paper")
    # Display tables are too wide for one column.
    text = text.replace("\\begin{center}\n\\small", "\\begin{table*}[t]\n\\centering\n\\small")
    text = text.replace(r"\end{center}", r"\end{table*}")
    return text


def main() -> int:
    source = SOURCE.read_text(encoding="utf-8").replace("\r\n", "\n")
    main_text, appendix = split_source(source)
    body, supp = convert_main(main_text), convert_supp(appendix)
    for name, content in (("body.tex", body), ("supp.tex", supp)):
        if r"\begin{center}" in content and name == "supp.tex":
            print(f"error: {name} still contains a single-column display table", file=sys.stderr)
            return 1
        header = f"% GENERATED by paper_cvpr/convert.py from paper/main.tex -- do not edit.\n"
        (HERE / name).write_text(header + content, encoding="utf-8", newline="\n")
    print(f"wrote body.tex ({body.count('table*') // 2} wide tables) and supp.tex")
    return 0


if __name__ == "__main__":
    sys.exit(main())
